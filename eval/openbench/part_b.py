"""Part B scoring, offline: `uv run python eval/openbench/part_b.py`.

Reference: the `raw transcription` column of .samajh/openbench/fleurs/test.tsv. Every transcripts file
under store.runs_dir("fleurs") is scored per system x condition x {all, subset} x {raw, norm}. An error
or empty output is scored as an empty hypothesis (all deletions) and counted. Items with no row are not
scored (n scored says how many were). Writes eval/openbench/tables-fleurs.md (aggregates only) and
eval/openbench/results-b.json (numbers and per-utterance edit counts by id).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import fleurs
import store
import wer

CONDITIONS = ("native16k", "phone")
SCOPES = ("all", "subset", "gemini100", "open50")
LABELS = {
    "whisper-large-v3": "(open baseline)",
    "indicwhisper-hi": "(open baseline)",
    "gemini-3-flash": "(closed reference)",
}


def label(system: str, n: int) -> str:
    if system == "gemini-3.1-pro-partial":
        return f"{system} (closed reference, partial: {n} clips, not used in schemes)"
    for prefix, tag in LABELS.items():
        if system.startswith(prefix):
            return f"{system} {tag}"
    return system


def main() -> None:
    manifest = fleurs.load_manifest()
    tsv = {r["tsv_id"]: r for r in fleurs.read_tsv()}
    refs = {m["id"]: tsv[m["tsv_id"]]["raw transcription"] for m in manifest}
    refs_tx = {m["id"]: tsv[m["tsv_id"]]["transcription"] for m in manifest}
    # treatment -> (reference texts, wer.py text treatment)
    treatments = {"raw": (refs, "raw"), "norm": (refs, "norm"), "norm-tx": (refs_tx, "norm")}
    missing_lines = []
    in_subset = {m["id"]: m["subset"] for m in manifest}
    gem = fleurs.gemini100(manifest)
    in_scope = {
        "all": lambda i: True,
        "subset": lambda i: in_subset[i],
        "gemini100": lambda i: i in gem,
        "open50": lambda i: i in open50,
    }
    # The first 50 manifest rows with gemini100 true: what `asr_local.py --only-field gemini100 --limit 50` takes.
    open50 = set([m["id"] for m in manifest if m["id"] in gem][:50])
    n_scope = {
        "open50": len(open50),
        "gemini100": len(gem),
        "all": len(manifest),
        "subset": sum(in_subset.values()),
    }

    results: dict = {"manifest_sha256": fleurs.MANIFEST_SHA.read_text().split()[0], "cells": []}
    lines = [
        "# Part B: FLEURS hi_in test, WER and CER",
        "",
        "Generated by `eval/openbench/part_b.py`. Reference: `raw transcription`. Corpus rates, 95% percentile",
        "bootstrap over utterances (2,000 resamples, seed 20261114). `norm` = NFC, lower-case, punctuation and",
        "symbols (danda included) to spaces; numbers are not converted. `norm-tx` = `norm` against the `transcription` column. Error or empty outputs are scored as",
        "empty hypotheses (all deletions) and counted in the `err/empty` column. `n` is the items scored out",
        "of the scope (all 417 or the 250 subset); a row is printed only for a scope the system completes (results-b.json keeps the rest).",
        "",
        "| system | condition | scope | text | n | err/empty | WER % [95% CI] | CER % [95% CI] |",
        "|---|---|---|---|---|---|---|---|",
    ]
    runs = sorted(store.runs_dir("fleurs").glob("*.jsonl")) if store.runs_dir("fleurs").exists() else []
    for path in runs:
        system = path.stem
        latest = store.latest(store.read_jsonl(path))
        for cond in CONDITIONS:
            rows = {iid: r for (iid, c), r in latest.items() if c == cond and iid in refs}
            missing_lines.append(
                f"- {label(system, len(rows))} / {cond}: {len(refs) - len(rows)} of {len(refs)} manifest items "
                f"have no row yet ({sum(in_subset[i] for i in refs if i not in rows)} of "
                f"{n_scope['subset']} in the subset)"
            )
            if not rows:
                continue
            for scope in SCOPES:
                ids = sorted(i for i in rows if in_scope[scope](i))
                if not ids:
                    continue
                bad = [i for i in ids if rows[i].get("error") is not None or not rows[i]["text"].strip()]
                for treatment, (tref, wt) in treatments.items():
                    per = {}
                    for i in ids:
                        hyp = "" if rows[i].get("error") is not None else rows[i]["text"]
                        we, wn = wer.word_counts(tref[i], hyp, wt)
                        ce, cn = wer.char_counts(tref[i], hyp, wt)
                        per[i] = {"word_edits": we, "ref_words": wn, "char_edits": ce, "ref_chars": cn}
                    w = wer.bootstrap(
                        [p["word_edits"] for p in per.values()], [p["ref_words"] for p in per.values()]
                    )
                    c = wer.bootstrap(
                        [p["char_edits"] for p in per.values()], [p["ref_chars"] for p in per.values()]
                    )
                    results["cells"].append(
                        {
                            "system": system,
                            "condition": cond,
                            "scope": scope,
                            "treatment": treatment,
                            "n": len(ids),
                            "scope_n": n_scope[scope],
                            "error_or_empty": len(bad),
                            "wer": w,
                            "cer": c,
                            "per_utterance": per,
                        }
                    )
                    if len(ids) < n_scope[scope]:
                        continue  # incomplete scope: kept in results-b.json, not printed
                    lines.append(
                        f"| {label(system, len(rows))} | {cond} | {scope} | {treatment} | {len(ids)}/{n_scope[scope]} | {len(bad)} | "
                        f"{w[0] * 100:.1f} [{w[1] * 100:.1f}-{w[2] * 100:.1f}] | {c[0] * 100:.1f} [{c[1] * 100:.1f}-{c[2] * 100:.1f}] |"
                    )
    head = lines.index(
        "| system | condition | scope | text | n | err/empty | WER % [95% CI] | CER % [95% CI] |"
    )
    lines[head:head] = [
        "Completeness (items with no transcript row):",
        "",
        *(missing_lines or ["- no runs"]),
        "",
    ]
    results["missing"] = missing_lines
    if not results["cells"]:
        lines.append("| (no transcripts yet) | | | | | | | |")
    (HERE / "tables-fleurs.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (HERE / "results-b.json").write_text(
        json.dumps(results, indent=1, sort_keys=True) + "\n", encoding="utf-8"
    )
    print("\n".join(lines))


if __name__ == "__main__":
    main()
