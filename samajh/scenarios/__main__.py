"""Command line for the scenario set. Run from the repository root."""

import argparse
import sys
from collections import Counter
from datetime import date
from pathlib import Path

from samajh.scenarios import build
from samajh.scenarios.model import CustomerState, ScenarioClass, YesNoOutcome
from samajh.types import RuleId, Verdict

STATS_BEGIN = "<!-- counts: generated by `python -m samajh.scenarios stats --write` -->"
STATS_END = "<!-- end of generated counts -->"


def _table(header: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def stats(directory: Path) -> str:
    """Counts from the files on disk, as the Markdown tables used in the datasheet."""
    scenarios = build.load_scenarios(directory)
    calls = {c.id: c for c in build.load_calls(directory)}
    languages = [language.value for language in build.LANGUAGES]
    base = [s for s in scenarios if s.language is build.LANGUAGES[0]]
    out = [f"Scenarios: {len(scenarios)} ({len(base)} base cases x {len(languages)} languages)", ""]

    by_target = Counter((s.target_rule, s.scenario_class) for s in base)
    out += [
        "Base cases by target rule and class (each appears once per language):",
        _table(
            ["Target rule", *(c.value for c in ScenarioClass), "Total"],
            [
                [rule.value, *(by_target[rule, c] for c in ScenarioClass), sum(by_target[rule, c] for c in ScenarioClass)]
                for rule in RuleId
                if any(by_target[rule, c] for c in ScenarioClass)
            ],
        ),
        "",
    ]

    by_language = Counter((s.language.value, s.scenario_class) for s in scenarios)
    out += [
        "Scenarios by language and class:",
        _table(
            ["Language", *(c.value for c in ScenarioClass), "Total"],
            [
                [lang, *(by_language[lang, c] for c in ScenarioClass), sum(by_language[lang, c] for c in ScenarioClass)]
                for lang in languages
            ],
        ),
        "",
    ]

    verdicts = Counter(s.gold.verdict for s in base)
    out += [
        "Base cases by gold verdict:",
        _table(["Verdict", "Base cases"], [[v.value, verdicts[v]] for v in Verdict]),
        "",
    ]

    flagged, unclear = Counter(), Counter()
    for s in base:
        flagged.update(rule for _, rule in s.gold.flag_keys())
        unclear.update(rule for _, rule in s.gold.unclear_keys())
    out += [
        "Base cases in which gold flags each rule, leaves it unclear, or does neither:",
        _table(
            ["Rule", "Flagged", "Unclear", "Neither"],
            [
                [rule.value, flagged[rule], unclear[rule], len(base) - flagged[rule] - unclear[rule]]
                for rule in RuleId
                if flagged[rule] or unclear[rule]
            ],
        ),
        "",
    ]

    e1 = Counter((s.customer_state, s.yes_no, calls[s.id].yes_no.outcome, s.gold.verdict) for s in base)
    out += [
        "Base cases by customer state, yes/no disposition, scripted yes/no outcome and gold verdict:",
        _table(
            ["Customer state", "Disposition", "Yes/no outcome", "Gold verdict", "Base cases"],
            [
                [state.value, disposition.value, outcome.value, verdict.value, count]
                for (state, disposition, outcome, verdict), count in sorted(
                    e1.items(), key=lambda item: [part.value for part in item[0]]
                )
            ],
        ),
        "",
    ]
    harmed = [s for s in base if s.customer_state is not CustomerState.informed]
    passed = [s for s in harmed if calls[s.id].yes_no.outcome is YesNoOutcome.confirmed]
    cleared = [s for s in harmed if s.gold.verdict is Verdict.clear]
    summary = (
        f"Customers who are not informed: {len(harmed)} base cases. The scripted yes/no call confirms "
        f"{len(passed)} of them ({', '.join(s.base for s in passed)}); gold is clear for {len(cleared)}."
    )
    out += [summary, ""]

    templated = Counter(s.template.remedy.value for s in base if s.template)
    out += [
        f"Base cases templated on an award: {sum(templated.values())} of {len(base)}. Remedy in the source award:",
        _table(["Remedy", "Base cases"], [[k, v] for k, v in sorted(templated.items())]),
        "",
    ]

    turns = Counter()
    for s in scenarios:
        call = calls[s.id]
        turns[s.language.value, "tb"] += sum(t.speaker.value == "customer" for t in call.teach_back.transcript.turns)
        turns[s.language.value, "yn"] += sum(t.speaker.value == "customer" for t in call.yes_no.transcript.turns)
    out += [
        "Customer turns to voice, per language:",
        _table(
            ["Language", "Teach-back", "Yes/no"], [[lang, turns[lang, "tb"], turns[lang, "yn"]] for lang in languages]
        ),
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m samajh.scenarios", description=__doc__)
    parser.add_argument("--dir", type=Path, default=build.DATA_DIR, help="data directory")
    commands = parser.add_subparsers(dest="command", required=True)
    build_cmd = commands.add_parser("build", help="regenerate gold.jsonl and calls.jsonl")
    build_cmd.add_argument("--force", action="store_true", help="replace frozen files that would change")
    freeze_cmd = commands.add_parser("freeze", help="record the hashes of the files on disk in FROZEN.json")
    freeze_cmd.add_argument("--reason", required=True, help="why the set is frozen or refrozen")
    freeze_cmd.add_argument("--date", type=date.fromisoformat, default=None, help="freeze date (default: today)")
    commands.add_parser("verify", help="fail if the files or the generator differ from FROZEN.json")
    check_cmd = commands.add_parser("check", help="compare gold with the rule engine on perfect input")
    check_cmd.add_argument("--path", choices=("beliefs", "extraction", "both"), default="both")
    check_cmd.add_argument("--strict", action="store_true", help="exit 1 on any disagreement")
    stats_cmd = commands.add_parser("stats", help="print the counts used in the datasheet")
    stats_cmd.add_argument("--write", action="store_true", help="replace the counts block in README.md")
    args = parser.parse_args(argv)

    if args.command == "build":
        built = build.write(args.dir, force=args.force)
        for name, sha in built.sha256().items():
            print(f"{sha}  {name}  ({built.count} rows)")
        return 0
    if args.command == "freeze":
        frozen = build.freeze(args.dir, on=args.date or date.today(), reason=args.reason)
        print(f"frozen version {frozen['version']} on {frozen['frozen_on']}, {frozen['count']} scenarios")
        for name, entry in frozen["files"].items():
            print(f"{entry['sha256']}  {name}")
        return 0
    if args.command == "verify":
        problems = build.verify(args.dir)
        for problem in problems:
            print(f"FAIL {problem}")
        if not problems:
            print(f"OK: files on disk and the generator match {build.FROZEN_FILE}")
        return 1 if problems else 0
    if args.command == "check":
        from samajh.scenarios import consistency  # the one place the rule engine is loaded

        problems = build.verify(args.dir)
        if problems:
            print("refusing to check: the set is not frozen or has drifted. Run verify.")
            return 1
        scenarios, calls = build.load_scenarios(args.dir), build.load_calls(args.dir)
        paths = ("beliefs", "extraction") if args.path == "both" else (args.path,)
        clean = True
        for path in paths:
            comparisons = consistency.check(scenarios, calls, path)
            print(consistency.report(comparisons, path))
            print()
            clean = clean and all(c.agrees and c.unclear_agrees for c in comparisons)
        return 1 if args.strict and not clean else 0
    text = stats(args.dir)
    if args.write:
        readme = args.dir / "README.md"
        before, _, rest = readme.read_text(encoding="utf-8").partition(STATS_BEGIN)
        _, _, after = rest.partition(STATS_END)
        readme.write_text(f"{before}{STATS_BEGIN}\n{text}\n{STATS_END}{after}", encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
