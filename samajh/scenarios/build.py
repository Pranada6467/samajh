"""Render the base cases in each language, write the two data files, and freeze them by hash.

`gold.jsonl` holds one scenario per line: record, beliefs, gold. `calls.jsonl` holds the two
scripted calls for each. Both are a pure function of the code in this package, so `build`
reproduces them byte for byte. `FROZEN.json` records their hashes; `verify` fails when a file on
disk, or what the code now generates, differs from the frozen hash.
"""

import hashlib
import json
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from samajh.scenarios.cases import BASE_CASES
from samajh.scenarios.model import REVIEW_LABEL, BaseCase, CallScripts, Scenario
from samajh.scenarios.phrases import BANKS
from samajh.scenarios.script import teach_back, yes_no
from samajh.types import Borrower, Language, LoanRecord

DATA_DIR = Path("data/scenarios")
GOLD_FILE = "gold.jsonl"
CALLS_FILE = "calls.jsonl"
FROZEN_FILE = "FROZEN.json"
LANGUAGES = (Language.hi, Language.hi_en, Language.ta, Language.kn)


def _scenario(case: BaseCase, case_number: int, language: Language) -> Scenario:
    facts = case.record
    record = LoanRecord(
        loan_id=f"TEST-LN-{case_number:02d}{LANGUAGES.index(language) + 1}",
        lender_type=facts.lender_type,
        borrower=Borrower(
            name=BANKS[language].borrower, dob=date(facts.birth_year, 1, 1), language=language
        ),
        loan_kind=facts.loan_kind,
        sanctioned_inr=facts.sanctioned_inr,
        disbursed_inr=facts.disbursed_inr,
        disbursed_on=facts.disbursed_on,
        products=facts.products,
    )
    return Scenario(
        id=f"{case.id}-{language.value}",
        base=case.id,
        language=language,
        text_review=REVIEW_LABEL[language],
        title=case.title,
        target_rule=case.target_rule,
        scenario_class=case.scenario_class,
        tags=case.tags,
        record=record,
        told=case.told,
        beliefs=case.beliefs,
        concerns=case.concerns,
        customer_state=case.customer_state,
        yes_no=case.yes_no,
        yes_no_basis=case.yes_no_basis,
        gold=case.gold,
        template=case.template,
    )


def scenarios() -> tuple[Scenario, ...]:
    """Every base case in every call language, in a fixed order."""
    return tuple(
        _scenario(case, number, language)
        for number, case in enumerate(BASE_CASES, start=1)
        for language in LANGUAGES
    )


def call_scripts(scenario: Scenario) -> CallScripts:
    """Both scripted calls for one scenario."""
    return CallScripts(
        id=scenario.id,
        language=scenario.language,
        text_review=scenario.text_review,
        teach_back=teach_back(scenario),
        yes_no=yes_no(scenario),
    )


def _canonical(value):
    """Sort the one set-valued field, whose order pydantic does not fix."""
    if isinstance(value, dict):
        return {k: sorted(v) if k == "features" else _canonical(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_canonical(v) for v in value]
    return value


def _jsonl(rows) -> bytes:
    lines = (
        json.dumps(_canonical(row.model_dump(mode="json")), ensure_ascii=False, sort_keys=True)
        for row in rows
    )
    return ("\n".join(lines) + "\n").encode("utf-8")


@dataclass(frozen=True)
class Built:
    """The generated bytes of both files."""

    gold: bytes
    calls: bytes
    count: int

    def sha256(self) -> dict[str, str]:
        return {
            GOLD_FILE: hashlib.sha256(self.gold).hexdigest(),
            CALLS_FILE: hashlib.sha256(self.calls).hexdigest(),
        }


def generate() -> Built:
    """Generate both files in memory."""
    rows = scenarios()
    return Built(gold=_jsonl(rows), calls=_jsonl(call_scripts(s) for s in rows), count=len(rows))


def load_scenarios(directory: Path = DATA_DIR) -> tuple[Scenario, ...]:
    """Read `gold.jsonl` from disk."""
    lines = (directory / GOLD_FILE).read_text(encoding="utf-8").splitlines()
    return tuple(Scenario.model_validate_json(line) for line in lines)


def load_calls(directory: Path = DATA_DIR) -> tuple[CallScripts, ...]:
    """Read `calls.jsonl` from disk."""
    lines = (directory / CALLS_FILE).read_text(encoding="utf-8").splitlines()
    return tuple(CallScripts.model_validate_json(line) for line in lines)


def _frozen(directory: Path) -> dict | None:
    path = directory / FROZEN_FILE
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _frozen_hashes(frozen: dict) -> dict[str, str]:
    return {name: frozen["files"][name]["sha256"] for name in (GOLD_FILE, CALLS_FILE)}


def write(directory: Path = DATA_DIR, *, force: bool = False) -> Built:
    """Write both files. Refuses to replace a frozen file with different bytes unless `force`."""
    built = generate()
    frozen = _frozen(directory)
    if frozen is not None and not force:
        changed = [name for name, sha in built.sha256().items() if _frozen_hashes(frozen)[name] != sha]
        if changed:
            raise SystemExit(
                f"refusing to write: {', '.join(changed)} would differ from the frozen hash. "
                "Rerun with --force, then log the change in CHANGELOG.md and refreeze."
            )
    directory.mkdir(parents=True, exist_ok=True)
    (directory / GOLD_FILE).write_bytes(built.gold)
    (directory / CALLS_FILE).write_bytes(built.calls)
    return built


def freeze(directory: Path = DATA_DIR, *, on: date, reason: str) -> dict:
    """Record the hashes of the files on disk. A second freeze with new hashes keeps the old ones in `history`."""
    hashes = {
        name: hashlib.sha256((directory / name).read_bytes()).hexdigest() for name in (GOLD_FILE, CALLS_FILE)
    }
    count = len((directory / GOLD_FILE).read_bytes().splitlines())
    previous = _frozen(directory)
    history = previous["history"] if previous else []
    if previous and _frozen_hashes(previous) == hashes:
        return previous
    entry = {"frozen_on": on.isoformat(), "reason": reason, "sha256": hashes, "count": count}
    frozen = {
        "version": len(history) + 1,
        "frozen_on": on.isoformat(),
        "count": count,
        "files": {name: {"sha256": sha, "count": count} for name, sha in hashes.items()},
        "history": [*history, entry],
    }
    (directory / FROZEN_FILE).write_text(json.dumps(frozen, indent=2) + "\n", encoding="utf-8")
    return frozen


def verify(directory: Path = DATA_DIR) -> list[str]:
    """Problems found, or an empty list: disk vs frozen hash, and generated bytes vs frozen hash."""
    frozen = _frozen(directory)
    if frozen is None:
        return [f"{FROZEN_FILE} is missing: the set is not frozen"]
    problems: list[str] = []
    generated = generate().sha256()
    for name, want in _frozen_hashes(frozen).items():
        path = directory / name
        if not path.exists():
            problems.append(f"{name}: missing")
            continue
        on_disk = hashlib.sha256(path.read_bytes()).hexdigest()
        if on_disk != want:
            problems.append(f"{name}: on disk {on_disk} differs from frozen {want}")
        if generated[name] != want:
            problems.append(f"{name}: the generator now produces {generated[name]}, frozen is {want}")
    return problems
